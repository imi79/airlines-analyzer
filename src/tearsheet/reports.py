"""Files for review: CSV exports, the coverage report and the Excel check sheet."""

from __future__ import annotations

import json
from datetime import datetime
from decimal import Decimal
from pathlib import Path

import duckdb
import pandas as pd
import xlsxwriter
import yaml

from tearsheet.config import DB_PATH, ROOT, load_issuers
from tearsheet.normalize.mapper import CONCEPT_MAP

OUT = ROOT / "docs" / "m1"
STATEMENTS = {"income": "Income statement", "balance": "Balance sheet", "cash_flow": "Cash flow"}


def _lines() -> dict[str, dict]:
    return yaml.safe_load(CONCEPT_MAP.read_text())["lines"]


def _connect(db_path: Path):
    return duckdb.connect(str(db_path), read_only=True)


def export_csv(db_path: Path = DB_PATH, out: Path = OUT) -> None:
    """Plain-text copies of the database, sorted, so any change shows up as a diff."""
    out.mkdir(parents=True, exist_ok=True)
    con = _connect(db_path)
    queries = {
        "filings.csv": "SELECT * FROM filings ORDER BY issuer, fiscal_year, filing_id",
        "facts.csv": """
            SELECT issuer, fiscal_year, period_end, concept,
                   CAST(value AS VARCHAR) AS value, CAST(value_tagged AS VARCHAR) AS value_tagged,
                   decimals,
                   currency, is_primary, restated, comparative, filing_id, source_ref, note,
                   footnote, warnings
            FROM facts ORDER BY issuer, fiscal_year, concept, filing_id""",
        "gaps.csv": "SELECT * FROM gaps ORDER BY issuer, fiscal_year, concept",
    }
    for name, sql in queries.items():
        con.execute(sql).df().to_csv(out / name, index=False)
    con.close()


def _millions(value) -> float:
    """For display only; the stored value keeps full precision."""
    return float(Decimal(str(value)) / Decimal(1_000_000))


def coverage_report(db_path: Path = DB_PATH, out: Path = OUT) -> dict[str, int]:
    """Markdown report: every v1 issuer, year and line is loaded or explained."""
    lines = _lines()
    con = _connect(db_path)
    facts = con.execute(
        "SELECT issuer, fiscal_year, concept, restated, note, footnote, warnings, source_ref, "
        "source_type FROM facts WHERE is_primary"
    ).df()
    gaps = con.execute("SELECT * FROM gaps").df()
    filings = con.execute("SELECT * FROM filings ORDER BY issuer, fiscal_year").df()
    con.close()

    md = [
        "# M1 coverage: every line loaded or explained",
        "",
        "Generated by `tearsheet report`. ✓ loaded · M entered by hand from the published "
        "statements (decision 0007) · R loaded, restated by a later filing · "
        "· covered by another line or not reported · ✗ missing (reason below).",
        "",
    ]
    totals = {"loaded": 0, "explained": 0, "missing": 0}
    summary = []
    for issuer in load_issuers():
        f = facts[facts.issuer == issuer.id]
        g = gaps[gaps.issuer == issuer.id]
        years = sorted(set(f.fiscal_year) | set(g.fiscal_year))
        applicable = [
            k for k, v in lines.items() if not v.get("applies_to") or issuer.type in v["applies_to"]
        ]
        rows = []
        for line_id in applicable:
            cells = []
            for year in years:
                hit = f[(f.fiscal_year == year) & (f.concept == line_id)]
                gap = g[(g.fiscal_year == year) & (g.concept == line_id)]
                if len(hit):
                    first = hit.iloc[0]
                    mark = "M" if first.source_type == "manual" else "✓"
                    cells.append("R" if first.restated else mark)
                    totals["loaded"] += 1
                elif len(gap) and not gap.iloc[0].counts_as_missing:
                    cells.append("·")
                    totals["explained"] += 1
                else:
                    cells.append("✗")
                    totals["missing"] += 1
            rows.append([lines[line_id]["label"], *cells])
        table = pd.DataFrame(rows, columns=["Line", *[f"FY{y}" for y in years]])
        own = filings[filings.issuer == issuer.id]
        md += [f"## {issuer.name}", ""]
        md += [
            "Filings: "
            + ", ".join(
                f"FY{r.fiscal_year} ({r.origin}, {r.language or '?'})" for r in own.itertuples()
            )
            + ".",
            "",
            _markdown(table),
            "",
        ]
        explained = []
        for r in g.sort_values(["concept", "fiscal_year"]).itertuples():
            mark = "✗" if r.counts_as_missing else "·"
            explained.append((mark, lines[r.concept]["label"], r.reason, r.fiscal_year))
        if explained:
            md += ["**Gaps**", ""]
            grouped: dict[tuple, list[int]] = {}
            for mark, label, reason, year in explained:
                grouped.setdefault((mark, label, reason), []).append(year)
            for (mark, label, reason), ys in grouped.items():
                md.append(f"- {mark} {label} ({_years(ys)}): {reason}")
            md.append("")
        notes: dict[tuple, list[int]] = {}
        for r in f.itertuples():
            for text in (None if r.source_type == "manual" else r.note, r.footnote):
                if isinstance(text, str) and text:
                    notes.setdefault((lines[r.concept]["label"], text.strip()), []).append(
                        r.fiscal_year
                    )
            if isinstance(r.warnings, str) and r.warnings:
                for w in json.loads(r.warnings):
                    notes.setdefault((lines[r.concept]["label"], f"⚠ {w}"), []).append(
                        r.fiscal_year
                    )
        if notes:
            md += ["**Notes and warnings**", ""]
            md += [f"- {label} ({_years(ys)}): {text}" for (label, text), ys in notes.items()]
            md.append("")
        summary.append(
            {
                "Issuer": issuer.name,
                "Years": _years(years),
                "Lines missing": int(g.counts_as_missing.sum()) if len(g) else 0,
            }
        )
    md[4:4] = ["## Summary", "", _markdown(pd.DataFrame(summary)), ""]
    out.mkdir(parents=True, exist_ok=True)
    (out / "coverage.md").write_text("\n".join(md) + "\n")
    return totals


def check_sheet(
    issuers: list[str], years: list[int], db_path: Path = DB_PATH, out: Path = OUT
) -> Path:
    """Excel sheet laid out like the published statements, for a tick-by-tick check."""
    lines = _lines()
    con = _connect(db_path)
    facts = con.execute("SELECT * FROM facts WHERE is_primary").df()
    gaps = con.execute("SELECT * FROM gaps").df()
    filings = con.execute("SELECT * FROM filings").df()
    con.close()
    names = {i.id: i for i in load_issuers()}

    out.mkdir(parents=True, exist_ok=True)
    path = out / "check_sheet.xlsx"
    book = xlsxwriter.Workbook(str(path))
    # A fixed creation date keeps the file identical from one run to the next.
    book.set_properties({"title": "M1 check sheet", "created": datetime(2026, 1, 1)})
    bold = book.add_format({"bold": True})
    head = book.add_format({"bold": True, "bg_color": "#DDE6F0", "border": 1, "text_wrap": True})
    section = book.add_format({"bold": True, "bg_color": "#F2F2F2"})
    number = book.add_format({"num_format": "#,##0;(#,##0)", "border": 1})
    text = book.add_format({"text_wrap": True, "border": 1, "valign": "top"})
    tick = book.add_format({"bg_color": "#FFF9DB", "border": 1})

    intro = book.add_worksheet("How to check")
    intro.set_column(0, 0, 110)
    for row, line in enumerate(
        [
            "Spot check for milestone M1 (decision 0004)",
            "",
            "1. Open the company's published annual report for the year (consolidated statements).",
            "2. For each line, compare the figure here with the published figure.",
            "3. Type ✓ in the yellow 'Matches?' column, or ✗ and the published figure.",
            "",
            "Reading the figures:",
            "- Amounts are in millions of the reporting currency, rounded for display only.",
            "- Costs and cash outflows are shown as positive amounts; the published accounts may",
            "  show them in brackets or with a minus sign. Only the amount needs to match.",
            "- Each year uses the latest figure published for it (a 2023 figure is read from the",
            "  2023 column of the 2024 report when that report restates it).",
            "- 'Label in the filing' is the electronic tag the figure was read from.",
            "- Lines marked 'not shown separately' are covered by another line (reason given).",
        ]
    ):
        intro.write(row, 0, line, bold if row == 0 else None)

    for issuer_id in issuers:
        issuer = names[issuer_id]
        ws = book.add_worksheet(issuer.name[:31])
        ws.set_column(0, 0, 44)
        ws.set_column(1, len(years), 12)
        ws.set_column(len(years) + 1, len(years) + 1, 46)
        ws.set_column(len(years) + 2, len(years) + 2, 10)
        ws.set_column(len(years) + 3, len(years) + 4, 24)
        ws.write(0, 0, f"{issuer.name}: {issuer.currency} millions", bold)
        sources = ", ".join(
            f"FY{r.fiscal_year}: {r.filing_id}"
            for r in filings[filings.issuer == issuer_id].sort_values("fiscal_year").itertuples()
            if r.fiscal_year in years or r.fiscal_year - 1 in years
        )
        ws.write(1, 0, f"Filings used: {sources}")
        header = [
            "Line",
            *[f"FY{y}" for y in years],
            "Label in the filing / note",
            "Matches?",
            "Published figure if different",
            "Comment",
        ]
        ws.write_row(3, 0, header, head)
        row = 4
        for statement, title in STATEMENTS.items():
            ws.write(row, 0, title, section)
            row += 1
            for line_id, spec in lines.items():
                if spec["statement"] != statement:
                    continue
                if spec.get("applies_to") and issuer.type not in spec["applies_to"]:
                    continue
                ws.write(row, 0, spec["label"], text)
                labels, reasons = [], []
                for col, year in enumerate(years, start=1):
                    hit = facts[
                        (facts.issuer == issuer_id)
                        & (facts.fiscal_year == year)
                        & (facts.concept == line_id)
                    ]
                    if len(hit):
                        r = hit.iloc[0]
                        ws.write_number(row, col, _millions(r.value), number)
                        concepts = " + ".join(
                            c.split(":", 1)[1] for c in json.loads(r.source_ref)["concepts"]
                        )
                        labels.append(concepts)
                        if isinstance(r.note, str):
                            reasons.append(r.note)
                        if isinstance(r.footnote, str):
                            reasons.append(r.footnote)
                    else:
                        gap = gaps[
                            (gaps.issuer == issuer_id)
                            & (gaps.fiscal_year == year)
                            & (gaps.concept == line_id)
                        ]
                        ws.write(
                            row,
                            col,
                            "not shown separately"
                            if len(gap) and not gap.iloc[0].counts_as_missing
                            else "missing",
                            text,
                        )
                        if len(gap):
                            reasons.append(gap.iloc[0].reason)
                described = "; ".join(dict.fromkeys(labels + reasons))
                ws.write(row, len(years) + 1, described, text)
                ws.write(row, len(years) + 2, "", tick)
                ws.write(row, len(years) + 3, "", tick)
                ws.write(row, len(years) + 4, "", tick)
                row += 1
        ws.freeze_panes(4, 1)
    book.close()
    return path


def manual_entries_report(db_path: Path = DB_PATH, out: Path = OUT) -> tuple[int, int]:
    """The figures entered by hand, with the prior-year control against the database."""
    from tearsheet.ingest.manual_figures import manual_figures

    lines = _lines()
    con = _connect(db_path)
    tagged = {
        (r[0], r[1], r[2]): Decimal(str(r[3]))
        for r in con.execute(
            "SELECT issuer, fiscal_year, concept, value FROM facts "
            "WHERE is_primary AND source_type = 'tagged'"
        ).fetchall()
    }
    entered = con.execute(
        "SELECT issuer, fiscal_year, concept, value, status, source_ref FROM facts "
        "WHERE source_type = 'manual' ORDER BY issuer, concept"
    ).df()
    con.close()
    md = [
        "# Figures entered by hand (decision 0007)",
        "",
        "Air France-KLM and ADP FY2025 have no electronic filing, so their figures were",
        "entered from the published statements Imane supplied (`config/manual_figures.yaml`).",
        "Each document's prior-year column is compared with the figure the database already",
        "holds for that year: a difference means a typing error or a restatement.",
        "",
    ]
    checked = matched = 0
    for issuer in load_issuers():
        _, facts, controls = manual_figures(issuer)
        if not facts:
            continue
        status = entered[entered.issuer == issuer.id].status.iloc[0]
        md += [
            f"## {issuer.name}: FY{facts[0].fiscal_year} (status: {status})",
            "",
            f"| Line | FY{facts[0].fiscal_year} | Page | FY{controls[0].fiscal_year} printed "
            "| FY{} in database | Control |".format(controls[0].fiscal_year),
            "| --- | --- | --- | --- | --- | --- |",
        ]
        by_line = {c.line: c for c in controls}
        for fact in facts:
            c = by_line[fact.line]
            held = tagged.get((issuer.id, c.fiscal_year, c.line))
            checked += 1
            if held is None:
                result = "no figure to compare"
            elif abs(held - c.printed) <= Decimal(500_000):
                result = "✓"
                matched += 1
            else:
                result = f"✗ differs by {_millions(c.printed - held):,.0f}"
            md.append(
                f"| {lines[fact.line]['label']} | {_millions(fact.value):,.0f} | {c.page} "
                f"| {_millions(c.printed):,.0f} | "
                f"{'–' if held is None else f'{_millions(held):,.0f}'} | {result} |"
            )
        md.append("")
    md[7:7] = [f"**Control: {matched} of {checked} prior-year figures match the database.**", ""]
    out.mkdir(parents=True, exist_ok=True)
    (out / "fy2025_entries.md").write_text("\n".join(md) + "\n")
    return matched, checked


def _years(years) -> str:
    years = sorted(set(int(y) for y in years))
    if not years:
        return ""
    if years == list(range(years[0], years[-1] + 1)) and len(years) > 2:
        return f"FY{years[0]}-FY{years[-1]}"
    return ", ".join(f"FY{y}" for y in years)


def _markdown(df: pd.DataFrame) -> str:
    header = "| " + " | ".join(map(str, df.columns)) + " |"
    rule = "| " + " | ".join("---" for _ in df.columns) + " |"
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, rule, *body])
