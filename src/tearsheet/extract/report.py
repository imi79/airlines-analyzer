"""M3 outputs in docs/m3/: what the AI read, what the checks decided, and the answer key score.

extractions.md     per company: the figures read from the report text by year, every
                   unverified value with its quote and the reasons, the AI calls and cost
extractions.csv    every line of every form the AI filled in, with the outcome of the checks
answer_key_score.md  the M3 checklist: the tool against the answer key
"""

from __future__ import annotations

import json
from decimal import Decimal
from pathlib import Path

import duckdb
import pandas as pd

from tearsheet.config import DB_PATH, ROOT, load_issuers
from tearsheet.extract.locator import items_for, load_items
from tearsheet.extract.scoring import KEY, extracted_from_db, load_key, score, summarise
from tearsheet.metrics.peers import fiscal_label
from tearsheet.metrics.reports import fmt

OUT = ROOT / "docs" / "m3"
STAR = " *"
OUTCOME_LABELS = {
    "verified_correct": "verified, matches the key",
    "verified_wrong": "**verified but wrong**",
    "unverified_correct": "right value, left unverified (waits for review)",
    "unverified_wrong": "wrong value, caught (left unverified)",
    "missing": "no value",
}


def _fmt(value, unit: str, currency: str) -> str:
    return fmt(value, unit, currency)


def _load(db_path: Path):
    con = duckdb.connect(str(db_path), read_only=True)
    facts = con.execute(
        "SELECT issuer, fiscal_year, period_end, concept, value, status, filing_id, "
        "comparative, source_ref FROM facts WHERE source_type = 'extracted' AND is_primary"
    ).df()
    log = con.execute("SELECT * FROM extraction_log").df()
    calls = con.execute("SELECT * FROM llm_calls").df()
    ends = con.execute(
        "SELECT issuer, fiscal_year, max(period_end) AS period_end FROM facts "
        "WHERE source_type NOT IN ('computed', 'extracted') AND is_primary GROUP BY 1, 2"
    ).df()
    con.close()
    return facts, log, calls, ends


def extraction_report(db_path: Path = DB_PATH, out: Path = OUT) -> dict[str, int]:
    """Write extractions.md and extractions.csv. Returns totals for the command line."""
    facts, log, calls, ends = _load(db_path)
    all_items = load_items()
    md = [
        "# M3 · Figures read from the report text",
        "",
        "Generated by `tearsheet report` from the facts database. The AI reads each report; code "
        "then checks every figure against the report (decision 0010). Only **verified** figures "
        "reach the tearsheet. \\* = unverified: kept off the tearsheet, listed under the "
        "company with its quote and the reason, waiting for your review in "
        "`config/extraction_reviews.yaml`. – = not found in the report. Every line the AI "
        "wrote is in `docs/m3/extractions.csv`.",
        "",
        "## Summary",
        "",
        "| Company | Reports read | Figures | Verified | Unverified \\* | Not found (own year) |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    body: list[str] = []
    totals = {"figures": 0, "verified": 0, "unverified": 0, "reports": 0, "not_read": 0,
              "listed": 0}  # fmt: skip
    for issuer in load_issuers():
        items = items_for(issuer.type, all_items)
        f = facts[facts.issuer == issuer.id]
        lg = log[log.issuer == issuer.id]
        cl = calls[calls.issuer == issuer.id]
        e = ends[ends.issuer == issuer.id].sort_values("fiscal_year")
        years = [int(y) for y in e.fiscal_year]
        labels = {
            int(r.fiscal_year): fiscal_label(int(r.fiscal_year), r.period_end.date())
            for r in e.itertuples()
        }
        read = int(cl.error.isna().sum()) if len(cl) else 0
        not_read = lg[lg.outcome.isin(["not_run", "error"])]
        verified = int((f.status.isin(["verified", "overridden"])).sum())
        unverified = int((f.status == "unverified").sum())
        have = {(int(r.fiscal_year), r.concept) for r in f.itertuples()}
        own_missing = sorted(
            {
                (int(r.fiscal_year), r.item)
                for r in lg[lg.outcome == "not_found"].itertuples()
                if r.fiscal_year == r.document_year and (int(r.fiscal_year), r.item) not in have
            }
        )
        totals["figures"] += len(f)
        totals["verified"] += verified
        totals["unverified"] += unverified
        totals["reports"] += read
        totals["not_read"] += len(not_read)
        md.append(
            f"| {issuer.name} | {read} | {len(f)} | {verified} | {unverified} | "
            f"{len(own_missing)} |"
        )

        body += [f"## {issuer.name} ({issuer.currency})", ""]
        body += [
            "| Figure | " + " | ".join(labels[y] for y in years) + " |",
            "| --- |" + " --- |" * len(years),
        ]
        for item_id, item in items.items():
            cells = []
            for y in years:
                hit = f[(f.fiscal_year == y) & (f.concept == item_id)]
                if not len(hit):
                    cells.append("–")
                    continue
                row = hit.iloc[0]
                text = _fmt(row.value, item["unit"], issuer.currency)
                cells.append(text + (STAR if row.status == "unverified" else ""))
            body.append(f"| {item['label']} | " + " | ".join(cells) + " |")
        body.append("")

        pending = f[f.status == "unverified"].sort_values(
            ["fiscal_year", "concept"], ascending=[False, True]
        )
        if len(pending):
            body += ["**Waiting for your review** (unverified, kept off the tearsheet)", ""]
            for row in pending.itertuples():
                ref = json.loads(row.source_ref)
                item = all_items[row.concept]
                quote = (ref.get("quotes") or [""])[0].strip().replace("\n", " ")
                where = ", ".join(x for x in ref.get("locations") or [] if x) or "not located"
                reasons = "; ".join(ref.get("checks_failed") or []) or "see notes"
                body.append(
                    f"- `{issuer.id} {row.fiscal_year} {row.concept}` · {item['label']} "
                    f"FY{row.fiscal_year}: **{_fmt(row.value, item['unit'], issuer.currency)}** "
                    f"(printed {ref.get('printed')}) from {row.filing_id}, {where}. "
                    f"Quote: “{quote[:300]}”. Why unverified: {reasons}."
                )
                totals["listed"] += 1
            body.append("")
        if own_missing:
            missing_text = ", ".join(f"{all_items[i]['label']} FY{y}" for y, i in own_missing)
            body += [f"**Not found in the year's own report:** {missing_text}.", ""]
        if len(not_read):
            body += ["**Reports not read:**", ""]
            for r in not_read.itertuples():
                reason = json.loads(r.reasons)[0] if r.reasons else ""
                body.append(f"- {r.document} (FY{r.document_year}): {reason}")
            body.append("")

    md += [
        f"| **Total** | {totals['reports']} | {totals['figures']} | {totals['verified']} | "
        f"{totals['unverified']} | |",
        "",
        *body,
        *_calls_section(calls),
    ]
    out.mkdir(parents=True, exist_ok=True)
    (out / "extractions.md").write_text("\n".join(md) + "\n")
    export = log.sort_values(["issuer", "document_year", "document", "fiscal_year", "item"]).copy()
    export["value"] = export["value"].map(
        lambda v: "" if pd.isna(v) else f"{Decimal(str(v)).normalize():f}"
    )
    export.to_csv(out / "extractions.csv", index=False)
    return totals


def _calls_section(calls: pd.DataFrame) -> list[str]:
    if not len(calls):
        return []
    ok = calls[calls.error.isna()]
    models = sorted(
        {f"{r.provider} · {r.model} · prompt {r.prompt_version}" for r in ok.itertuples()}
    )
    tokens_in = int(ok.input_tokens.fillna(0).sum())
    tokens_out = int(ok.output_tokens.fillna(0).sum())
    cost = ok.cost_usd.dropna()
    lines = [
        "## AI calls",
        "",
        f"- Reports read: {len(ok)} (one request each). Model: {'; '.join(models) or '–'}.",
        f"- Tokens: {tokens_in:,} in, {tokens_out:,} out"
        + (
            f"; cost USD {float(cost.sum()):.2f}."
            if len(cost)
            else " (no price set in `config/models.yaml`, so no cost shown)."
        ),
        "- Every answer is recorded under `records/llm/`; a rerun replays the records at no "
        "cost and gives the same result.",
        "",
    ]
    return lines


def score_report(
    db_path: Path = DB_PATH,
    out: Path = OUT,
    key_path: Path = KEY,
    flagged: tuple[int, int] | None = None,
):
    """Write answer_key_score.md. Returns the summary, or None without an answer key.
    `flagged`: (unverified figures listed for review, unverified figures in the database)."""
    if not key_path.exists():
        return None
    key = load_key(key_path)
    scored = score(key, extracted_from_db(db_path))
    s = summarise(scored)
    items = load_items()
    names = {i.id: i for i in load_issuers()}
    tick = {True: "[x]", False: "[ ]"}
    md = [
        "# M3 · Answer key score",
        "",
        "Generated by `tearsheet report`. The answer key (`docs/m3/answer_key.csv`) was read by "
        "code without AI and without the extraction code (decision 0012). It is compared with "
        "the value the tool keeps for each figure, using the status the checks gave before any "
        "review. Values match when they agree within the rounding of the printed figures.",
        "",
        f"- {tick[s.no_wrong_verified]} **No wrong value marked verified**: "
        f"{s.counts['verified_wrong']} of {s.total}.",
        f"- {tick[s.enough_verified]} **At least 80% verified automatically**: "
        f"{s.counts['verified_correct']} of {s.total} ({s.share_verified:.0%}).",
        *(
            [
                f"- {tick[flagged[0] == flagged[1]]} **Every unverified value visibly flagged**: "
                f"{flagged[0]} of {flagged[1]} unverified figures are listed with their reason in "
                "`docs/m3/extractions.md` and marked \\*; every ratio that uses one is marked "
                "\\* in `docs/m2/metrics.md` and `docs/m2/peers.md`."
            ]
            if flagged
            else []
        ),
        "",
        "| Outcome | Count |",
        "| --- | --- |",
        *(f"| {OUTCOME_LABELS[o]} | {n} |" for o, n in s.counts.items()),
        "",
        "| Company | Year | Figure | Answer key | Tool | Outcome | Where the key read it |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for x in scored:
        k = x.key
        issuer = names[k.issuer]
        unit = items[k.item]["unit"]
        tool = "–"
        if x.extracted is not None:
            tool = _fmt(x.extracted.value, unit, issuer.currency)
            if x.extracted.status != "verified":
                tool += STAR
            if x.extracted.reviewed:
                tool += " (reviewed)"
        md.append(
            f"| {issuer.name} | FY{k.fiscal_year} | {items[k.item]['label']} | "
            f"{_fmt(k.value, unit, issuer.currency)} (printed {k.printed}) | {tool} | "
            f"{OUTCOME_LABELS[x.outcome]} | {k.document}, {k.location} |"
        )
    out.mkdir(parents=True, exist_ok=True)
    (out / "answer_key_score.md").write_text("\n".join(md) + "\n")
    return s


def write_all() -> tuple[dict[str, int], object]:
    totals = extraction_report()
    return totals, score_report(flagged=(totals["listed"], totals["unverified"]))
