"""The Excel backup (M6): five sheets, every metric a live formula a reviewer can follow.

    Inputs     every figure from the filings, the reports and the hand entries, all years,
               each value cell named <line>_FY<year> (for example revenue_FY2025)
    Metrics    every metric and year as a live formula on those names
               (=ebitda_FY2025/revenue_FY2025), next to the app's value and the difference
    Peers      the peer table: each company's figure, the median and the rank as formulas
    Extracted  figures read from the report text, with the quote and the checks
    Manifest   the run manifest: filings and fingerprints, models, prompt versions

Values are stored in full units with all their decimals; only the cell formats round.
"""

from __future__ import annotations

import io
from decimal import Decimal
from pathlib import Path

import xlsxwriter
from xlsxwriter.utility import xl_rowcol_to_cell

from tearsheet.metrics.engine import load_catalog
from tearsheet.render import sheet_formulas as sf
from tearsheet.render.library import Library, key, split
from tearsheet.render.tearsheet import peer_table_for

ORIGINALS = ("tagged", "manual", "extracted")
SOURCE_WORDS = {
    "tagged": "Filing fact",
    "manual": "Entered by hand from the statements",
    "extracted": "Read from the report text",
    "computed": "Computed",
}
STATUS_WORDS = {"verified": "verified", "overridden": "approved by the analyst",
                "unverified": "awaiting review"}  # fmt: skip


def _formats(wb) -> dict:
    base = {"font_name": "Arial", "font_size": 9}
    fmt = {
        "amount": '#,##0.0,,"m"',
        "pct": "0.0%",
        "x": '0.00"x"',
        "count": "#,##0",
        "years": "0.0",
        "per_km": "0.0000",
        "per_passenger": "0.00",
        "rank": "0",
    }
    out = {u: wb.add_format(base | {"num_format": f}) for u, f in fmt.items()}
    out["text"] = wb.add_format(base | {"text_wrap": False})
    out["wrap"] = wb.add_format(base | {"text_wrap": True, "valign": "top"})
    out["head"] = wb.add_format(base | {"bold": True, "bg_color": "#1F4E79",
                                        "font_color": "white", "text_wrap": True,
                                        "valign": "top"})  # fmt: skip
    out["title"] = wb.add_format(base | {"bold": True, "font_size": 12})
    out["note"] = wb.add_format(base | {"italic": True, "font_color": "#555555"})
    out["diff"] = wb.add_format(base | {"num_format": "0.00E+00"})
    out["bold"] = wb.add_format(base | {"bold": True})
    return out


def write(lib: Library, ts: dict, manifest: dict, target: Path | io.BytesIO | None = None,
          cached_results: bool = True) -> bytes | Path:  # fmt: skip
    """Write the workbook to `target` (a path), or return its bytes. `cached_results=False`
    leaves the formula results empty, so only a real recalculation can fill them (the test
    uses it to prove LibreOffice recalculates)."""
    buffer = io.BytesIO() if target is None or isinstance(target, io.BytesIO) else None
    wb = xlsxwriter.Workbook(buffer if buffer is not None else str(target),
                             {"in_memory": True, "strings_to_numbers": False})  # fmt: skip
    f = _formats(wb)
    issuer = ts["issuer"]
    title = f"{ts['name']}, {ts['period_label']}: credit tearsheet backup"
    _inputs(wb, f, lib, issuer, title)
    _metrics(wb, f, lib, issuer, title, cached_results)
    _peers(wb, f, lib, ts, cached_results)
    _extracted(wb, f, lib, issuer)
    _manifest(wb, f, manifest)
    wb.set_properties({"title": title, "subject": "Credit tearsheet backup",
                       "comments": "Generated by Airline Credit Tearsheet"})  # fmt: skip
    wb.close()
    if buffer is not None:
        data = buffer.getvalue()
        if isinstance(target, io.BytesIO):
            target.write(data)
        return data
    return target


def _sorted_keys(lib: Library, issuer: str, kinds: tuple[str, ...]) -> list[str]:
    keys = [
        k for k, x in lib.figures.items() if x["issuer"] == issuer and x["source_type"] in kinds
    ]
    return sorted(
        keys, key=lambda k: (lib.figures[k]["label"].lower(), lib.figures[k]["fiscal_year"])
    )


def _inputs(wb, f, lib: Library, issuer: str, title: str) -> None:
    ws = wb.add_worksheet("Inputs")
    ws.write(0, 0, title, f["title"])
    note = ("Every figure the metrics use, as filed or read, in full units of the reporting "
            "currency. Each value cell is named <line>_FY<year>.")  # fmt: skip
    ws.write(1, 0, note, f["note"])
    heads = ["Name", "Figure", "Fiscal year", "Value", "Unit", "Source", "Filing or document",
             "Tagged as / line / quote", "Status"]  # fmt: skip
    ws.write_row(3, 0, heads, f["head"])
    row = 4
    for k in _sorted_keys(lib, issuer, ORIGINALS):
        x = lib.figures[k]
        src = x["source"]
        if x["source_type"] == "tagged":
            where, what = x["filing_id"], ", ".join(src.get("concepts") or [])
        elif x["source_type"] == "manual":
            where = x["filing_id"]
            what = (
                f"{', '.join(src.get('concepts') or [])} ({', '.join(src.get('fact_ids') or [])})"
            )
        else:
            where = src.get("document")
            what = (src.get("quotes") or [""])[0].strip()[:250]
        unit = x["unit"]
        ws.write(row, 0, sf.excel_name(k), f["text"])
        ws.write(row, 1, x["label"], f["text"])
        ws.write_number(row, 2, x["fiscal_year"], f["rank"])
        ws.write_number(row, 3, float(Decimal(x["value"])), f.get(unit, f["text"]))
        ws.write(row, 4, unit if unit != "amount" else x["currency"], f["text"])
        ws.write(row, 5, SOURCE_WORDS[x["source_type"]], f["text"])
        ws.write(row, 6, where or "", f["text"])
        ws.write(row, 7, what, f["text"])
        ws.write(row, 8, STATUS_WORDS.get(x["status"], x["status"]), f["text"])
        wb.define_name(sf.excel_name(k), f"=Inputs!{xl_rowcol_to_cell(row, 3, True, True)}")
        row += 1
    ws.set_column(0, 0, 30)
    ws.set_column(1, 1, 38)
    ws.set_column(2, 2, 10)
    ws.set_column(3, 3, 14)
    ws.set_column(4, 5, 16)
    ws.set_column(6, 6, 42)
    ws.set_column(7, 7, 60)
    ws.set_column(8, 8, 16)
    ws.freeze_panes(4, 2)
    ws.autofilter(3, 0, row - 1, len(heads) - 1)


def metric_rows(lib: Library, issuer: str) -> list[dict]:
    """One row per metric and year shown on the Metrics sheet (also used by the check)."""
    catalog = load_catalog()
    kind = lib.issuers[issuer]["type"]
    rows = []
    for metric, spec in catalog.items():
        if spec.get("applies_to") and kind not in spec["applies_to"]:
            continue
        for year in lib.years(issuer):
            k = key(issuer, metric, year)
            x = lib.figures.get(k)
            rows.append({"metric": metric, "label": spec["label"], "year": year, "key": k,
                         "unit": spec["unit"], "figure": x,
                         "reason": None if x else lib.why_missing(k)})  # fmt: skip
    return rows


def _metrics(wb, f, lib: Library, issuer: str, title: str, cached: bool) -> None:
    ws = wb.add_worksheet("Metrics")
    ws.write(0, 0, title, f["title"])
    ws.write(1, 0, "Each value is a live formula on the Inputs (click a cell to read it). "
             "\"App value\" is the figure the tearsheet shows; the difference should be zero.",
             f["note"])  # fmt: skip
    heads = ["Metric", "Fiscal year", "Value (live formula)", "App value", "Difference",
             "Formula", "Status", "Definition"]  # fmt: skip
    ws.write_row(3, 0, heads, f["head"])
    catalog = load_catalog()
    row = 4
    for r in metric_rows(lib, issuer):
        x, unit = r["figure"], r["unit"]
        num = f.get(unit, f["text"])
        ws.write(row, 0, r["label"], f["text"])
        ws.write_number(row, 1, r["year"], f["rank"])
        if x is None:
            text = "n.m." if (r["reason"] or "").startswith("n.m.") else "n.a."
            ws.write(row, 2, text, f["text"])
            ws.write(row, 5, r["reason"] or "", f["text"])
        else:
            if x["source_type"] == "computed":
                formula = sf.to_excel(sf.resolve(lib, r["key"]))
                wb.define_name(
                    sf.excel_name(r["key"]), f"=Metrics!{xl_rowcol_to_cell(row, 2, True, True)}"
                )
            else:  # the metric is the line itself (passengers): point at the input
                formula = "=" + sf.excel_name(r["key"])
            value = float(Decimal(x["value"]))
            if cached:
                ws.write_formula(row, 2, formula, num, value)
            else:
                ws.write_formula(row, 2, formula, num)
            ws.write_number(row, 3, value, num)
            c, d = xl_rowcol_to_cell(row, 2), xl_rowcol_to_cell(row, 3)
            ws.write_formula(row, 4, f"={c}-{d}", f["diff"], 0 if cached else None)
            ws.write_string(row, 5, formula, f["text"])  # the formula as text, for reading
            ws.write(row, 6, STATUS_WORDS.get(x["status"], x["status"]), f["text"])
        ws.write(row, 7, " ".join(str(catalog[r["metric"]]["definition"]).split()), f["text"])
        row += 1
    ws.set_column(0, 0, 30)
    ws.set_column(1, 1, 10)
    ws.set_column(2, 3, 16)
    ws.set_column(4, 4, 11)
    ws.set_column(5, 5, 52)
    ws.set_column(6, 6, 16)
    ws.set_column(7, 7, 80)
    ws.freeze_panes(4, 2)
    ws.autofilter(3, 0, row - 1, len(heads) - 1)


def _peers(wb, f, lib: Library, ts: dict, cached: bool) -> None:
    ws = wb.add_worksheet("Peers")
    table = peer_table_for(lib, ts)
    members = table["members"]
    names = [lib.issuers[m]["name"] for m in members]
    ws.write(0, 0, f"{table['label']}, peer year {table['peer_year']}", f["title"])
    ws.write(1, 0, "Each company's own figure (a value, with its source on the Inputs sheet of "
             "its own workbook); the median and the rank are live formulas over the verified "
             "figures. Rank 1 is the strongest.", f["note"])  # fmt: skip
    heads = ["Metric"] + [f"{n} {table['fiscal_years'][m] or ''}".strip()
                          for n, m in zip(names, members, strict=True)]  # fmt: skip
    heads += ["Median (live formula)", "App median", f"{lib.issuers[ts['issuer']]['name']} rank"]
    ws.write_row(3, 0, heads, f["head"])
    row = 4
    for r in table["rows"]:
        num = f.get(r["unit"], f["text"])
        ws.write(row, 0, r["label"], f["text"])
        for n, m in enumerate(members, start=1):
            c = r["cells"][m]
            if c.get("rendered"):
                ws.write_number(row, n, float(Decimal(lib.figures[c["key"]]["value"])), num)
            else:
                ws.write(row, n, "n.m." if c.get("nm") else ("awaiting review" if c.get("key")
                         else "n.a."), f["text"])  # fmt: skip
        first, last = xl_rowcol_to_cell(row, 1), xl_rowcol_to_cell(row, len(members))
        col = len(members) + 1
        if r["median"] is not None:
            mid = float(Decimal(r["median"]))
            ws.write_formula(row, col, f"=MEDIAN({first}:{last})", num, mid if cached else None)
            ws.write_number(row, col + 1, mid, num)
        own = members.index(ts["issuer"]) + 1 if ts["issuer"] in members else None
        own_cell = r["cells"].get(ts["issuer"], {})
        if own and own_cell.get("rank") and r["higher_is_better"] is not None:
            order = 0 if r["higher_is_better"] else 1
            formula = f"=RANK({xl_rowcol_to_cell(row, own)},{first}:{last},{order})"
            ws.write_formula(row, col + 2, formula, f["rank"], own_cell["rank"] if cached else None)
        row += 1
    ws.set_column(0, 0, 32)
    ws.set_column(1, len(members) + 3, 20)
    ws.freeze_panes(4, 1)


def _extracted(wb, f, lib: Library, issuer: str) -> None:
    ws = wb.add_worksheet("Extracted")
    ws.write(0, 0, "Figures read from the report text by the AI, each checked by code against "
             "its quote", f["title"])  # fmt: skip
    heads = ["Figure", "Fiscal year", "Value", "Status", "Quote", "Where", "Document",
             "Printed as", "Checks failed", "Review", "Model and prompt"]  # fmt: skip
    ws.write_row(2, 0, heads, f["head"])
    row = 3
    for k in _sorted_keys(lib, issuer, ("extracted",)):
        x = lib.figures[k]
        src = x["source"]
        ws.write(row, 0, x["label"], f["wrap"])
        ws.write_number(row, 1, x["fiscal_year"], f["rank"])
        ws.write_number(row, 2, float(Decimal(x["value"])), f.get(x["unit"], f["text"]))
        ws.write(row, 3, STATUS_WORDS.get(x["status"], x["status"]), f["wrap"])
        ws.write(row, 4, " | ".join(q.strip() for q in src.get("quotes") or []), f["wrap"])
        ws.write(row, 5, ", ".join(src.get("locations") or []), f["wrap"])
        ws.write(row, 6, src.get("document") or "", f["wrap"])
        ws.write(row, 7, src.get("printed") or "", f["wrap"])
        ws.write(row, 8, "; ".join(src.get("checks_failed") or []), f["wrap"])
        review = src.get("review")
        ws.write(row, 9, "" if not review else (
            f"{review.get('action')} by {review.get('by')} on {review.get('on')}: "
            f"{review.get('reason')}"), f["wrap"])  # fmt: skip
        ws.write(row, 10, f"{src.get('model', '')} {src.get('prompt_version', '')}".strip(),
                 f["wrap"])  # fmt: skip
        row += 1
    for col, width in enumerate([28, 10, 14, 16, 70, 14, 34, 18, 40, 30, 22]):
        ws.set_column(col, col, width)
    ws.freeze_panes(3, 1)


def _manifest(wb, f, m: dict) -> None:
    ws = wb.add_worksheet("Manifest")
    ws.write(0, 0, "Run manifest", f["title"])
    t, d = m["tearsheet"], m["ai"]["drafting"]
    rows = [
        ("Company", t["name"]), ("Fiscal year", t["period"]), ("Currency", t["currency"]),
        ("Peer group", f"{t['peer_group']}, peer year {t['peer_year']}"),
        ("Exported at (UTC)", m["exported_at"]), ("Code version", m["code_version"]),
        ("Mode", m["mode"]),
        ("Commentary model", f"{d['provider']} {d['model']}"),
        ("Commentary prompt version", d["prompt_version"]),
        ("Commentary AI calls and tokens",
         f"{d['calls']} calls, {d['input_tokens']:,} in, {d['output_tokens']:,} out"
         if d["calls"] else "n.a."),
        ("Commentary recorded at", d["recorded_at"] or "n.a."),
        ("Fact sheet fingerprint", m["fact_sheet_fingerprint"] or "n.a."),
        ("Commentary matches the figures", "yes" if m["commentary_matches_figures"] else "no"),
        ("Extraction (figures read from reports)", "; ".join(
            f"{e['provider']} {e['model']}, prompt {e['prompt_version']} ({e['figures']} figures)"
            for e in m["ai"]["extraction"]) or "none"),
        ("Events of the year", "; ".join(
            f"{e['model']}, prompt {e['prompt_version']}" for e in m["ai"]["events"]) or "none"),
        ("Analyst edits", f"{m['analyst']['edited_sentences']} sentences edited, "
                          f"{m['analyst']['sentences_with_untraced_figures']} with a figure "
                          "not traced to a source"),
        ("Analyst view included", "yes" if m["analyst"]["analyst_view"] else "no"),
        ("Source figures traced", m["figures_traced"]),
    ]  # fmt: skip
    for n, (k, v) in enumerate(rows, start=2):
        ws.write(n, 0, k, f["bold"])
        ws.write(n, 1, v, f["text"])
    row = len(rows) + 3
    ws.write_row(row, 0, ["Filing", "Company", "Fiscal year", "Origin", "SHA-256", "Figures",
                          "Link"], f["head"])  # fmt: skip
    for fid, e in m["filings"].items():
        row += 1
        ws.write_row(row, 0, [fid, e["company"] or "", e["fiscal_year"] or "", e["origin"] or "",
                              e["sha256"] or "", e["figures"]], f["text"])  # fmt: skip
        if e.get("link"):
            ws.write_url(row, 6, e["link"], f["text"], "open")
    row += 2
    ws.write_row(row, 0, ["Document read by the AI", "Kind", "File", "", "SHA-256", "Figures",
                          "Link"], f["head"])  # fmt: skip
    for doc, e in m["documents"].items():
        row += 1
        ws.write_row(row, 0, [doc, e["kind"], e.get("file") or "", "", e["sha256"] or "",
                              e["figures"]], f["text"])  # fmt: skip
        if e.get("link"):
            ws.write_url(row, 6, e["link"], f["text"], "open")
    ws.set_column(0, 0, 44)
    ws.set_column(1, 1, 60)
    ws.set_column(2, 3, 16)
    ws.set_column(4, 4, 66)
    ws.set_column(5, 6, 10)


